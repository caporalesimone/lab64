"""Instruction manuals of a C64 program: HTML source -> HTML + PDF (WeasyPrint), with the Lab64 manual themes. Copyright (c) 2026 - Simone Caporale

Runs in lab64-pdf-gen (WeasyPrint). From the host: lab64 manual [SRC ...] [options]; from a project script in that container:
    from c64manual import build
    build("docs/manual/manual.html", values={"MONSTER_ROWS": rows}, pdf_name="Game_Manual.pdf")

A project can have SEVERAL manuals (languages, a full and a short one, A5 and A4): one HTML source each. C64_MANUAL_SRC lists
them (space separated, shell patterns allowed, e.g. "manual/*.html"); lab64 manual builds them all, or the ones given.

Source: an HTML file where every <div class="page"> is one page; a page with the class "cover" is not numbered, the others get
"- N -" at the bottom. Settings of ONE manual can be written in its source, in the head:
    <meta name="lab64:format" content="A4">           page format: A4, A5 (default), A6, Letter, or "<w>x<h>" in mm (e.g. 170x240)
    <meta name="lab64:base" content="plain">          Lab64 base theme (containers/pdf-gen/themes/<name>.css) or "none"
    <meta name="lab64:theme" content="short.css">     project theme, path relative to the source
    <meta name="lab64:pdf" content="Game_EN.pdf">     PDF file name
Order: option of build() / lab64 manual > meta of the source > lab64.env (C64_MANUAL_FORMAT, C64_MANUAL_BASE, C64_MANUAL_THEME,
C64_MANUAL_PDF) > default (A5, c64, none, <source name>.pdf).
How the format reaches the PDF: CSS. The generator adds "@page { size: W H }" and the page box size (--page-w, --page-h) after the
base theme and before the project theme; WeasyPrint lays out every div.page on a sheet of that size. The type sizes stay those
of the theme: a manual in another format usually wants its own theme (sizes, margins) and its own text.

The generator:
  1. fills the placeholders {{NAME}} with the values given by the project (a missing placeholder is an error; one left without a
     value is reported);
  2. resolves relative links (src=, href=): a file that exists next to the source is linked there, anything else is looked for
     in the output folder (e.g. pictures generated by the project into out/work/manual/img/);
  3. puts the theme into the page: the base theme (a theme may start with "/* lab64:extends <name> */": its parent comes first),
     the page format, then the project theme (it overrides variables and rules); the source's own <link rel="stylesheet"> last;
  4. turns every <kbd>X</kbd> into an SVG key cap (text centred exactly; colours --key-face, --key-ink, --key-shadow of the theme);
  5. writes the HTML and the PDF into the output folder and reports the pages whose content does not fit (cut).
     strict=True (lab64 manual --strict): an overflowing page, a placeholder without value, or an overflow check that cannot run
     (it uses WeasyPrint internals) stops with exit 1 (release builds); without strict they are warnings."""
import glob, html as _html, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "common", "py"))
from lab64env import setting as _setting  # noqa: E402  (containers/common/py/lab64env.py: the one reader of lab64.env)

LAB64 = os.environ.get("LAB64") or os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
THEMES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "themes")
OUT = os.path.join("out", "work", "manual")
FORMATS = {"A4": (210, 297), "A5": (148, 210), "A6": (105, 148), "LETTER": (215.9, 279.4)}


def setting(name, default=None):
    """a C64_MANUAL_* setting: environment first, then lab64.env of the project (current folder; containers/common/py/lab64env.py)"""
    return _setting(name, default)


def sources():
    """the manual sources of the project: C64_MANUAL_SRC (patterns allowed), default manual/manual.html"""
    out = []
    for pat in setting("C64_MANUAL_SRC", os.path.join("manual", "manual.html")).split():
        out += sorted(glob.glob(pat)) or [pat]
    return out


def meta(html, key):
    """value of <meta name="lab64:key" content="..."> in the source, or None"""
    m = re.search(r'<meta\s+name="lab64:%s"\s+content="([^"]*)"' % key, html, re.I)
    return m.group(1).strip() if m else None


def page_format(fmt):
    """(width, height) in mm of a format name or "<w>x<h>" """
    f = fmt.strip().upper()
    if f in FORMATS:
        return FORMATS[f]
    m = re.match(r"^(\d+(?:\.\d+)?)\s*X\s*(\d+(?:\.\d+)?)$", f)
    if not m:
        sys.exit("manual: page format '%s' (A4, A5, A6, Letter or <w>x<h> in mm)" % fmt)
    return float(m.group(1)), float(m.group(2))


def base_css(name):
    """CSS of a Lab64 base theme, with its parents first (/* lab64:extends <name> */)"""
    p = os.path.join(THEMES, name + ".css")
    if not os.path.isfile(p):
        sys.exit("manual: no Lab64 theme '%s' (%s)" % (name, ", ".join(sorted(f[:-4] for f in os.listdir(THEMES)))))
    css = open(p, encoding="utf-8").read()
    m = re.search(r"/\*\s*lab64:extends\s+([\w-]+)\s*\*/", css)
    return (base_css(m.group(1)) + "\n" if m else "") + "/* Lab64 theme %s */\n%s" % (name, css)


def themes(base=None, theme=None, fmt=None):
    """CSS text: base theme (Lab64), page format, project theme"""
    base = base or setting("C64_MANUAL_BASE", "c64")
    parts = [] if base == "none" else [base_css(base)]
    w, h = page_format(fmt or setting("C64_MANUAL_FORMAT", "A5"))
    parts.append("/* page format */\n@page { size: %gmm %gmm; margin: 0 }\n:root { --page-w: %gmm; --page-h: %gmm }" % (w, h, w, h))
    if theme:
        if not os.path.isfile(theme):
            sys.exit("manual: project theme %s not found" % theme)
        parts.append("/* project theme %s */\n%s" % (theme, open(theme, encoding="utf-8").read()))
    return "\n".join(parts)


def var(css, name, default):
    """last value of the CSS variable --name in css (the project theme comes last, so it wins)"""
    v = re.findall(r"--%s\s*:\s*([^;}]+)" % name, css)
    return v[-1].strip() if v else default


# key caps: drawn in font units of DejaVu Sans Mono (2048 per em, advance 1233, capital height 1493). In HTML the browser snaps
# the baseline to whole pixels and the offset changed from key to key; inside the SVG the position is exact and equal for all.
U, ADV, CAP = 2048, 1233, 1493
KH, PADX, BRD, RAD, SH = 2908, 941, 196, 785, 314      # 1.42 em high; 1.2 mm padding; 0.25 mm border; 1 mm radius; 0.4 mm shadow


def kbd(text, face, ink, shadow):
    t = _html.unescape(text)
    w = max(KH, len(t) * ADV + 2 * PADX)
    th = KH + SH
    base = KH / 2 + CAP / 2                              # capitals and digits centred vertically
    return (f'<svg class="key" viewBox="0 0 {w} {th}" style="width:{w / U:.4f}em;height:{th / U:.4f}em;'
            f'vertical-align:-{(th - base) / U:.4f}em">'
            f'<rect x="{BRD / 2}" y="{BRD / 2 + SH}" width="{w - BRD}" height="{KH - BRD}" rx="{RAD}" fill="{shadow}"/>'
            f'<rect x="{BRD / 2}" y="{BRD / 2}" width="{w - BRD}" height="{KH - BRD}" rx="{RAD}" fill="{face}" '
            f'stroke="{ink}" stroke-width="{BRD}"/>'
            f'<text x="{w / 2}" y="{base:.0f}" text-anchor="middle" font-family="DejaVu Sans Mono" font-size="{U}" '
            f'fill="{ink}">{_html.escape(t)}</text></svg>')


def relink(html, src_dir, out_dir):
    """relative src= / href= : to the file next to the source if it exists there, else left as is (= in the output folder)"""
    def fix(m):
        url = m.group(2)
        if re.match(r"^([a-z][a-z0-9+.-]*:|#|/)", url, re.I) or not url:
            return m.group(0)
        path = url.split("#")[0].split("?")[0]
        if os.path.exists(os.path.join(src_dir, path)):
            url = os.path.relpath(os.path.join(src_dir, path), out_dir) + url[len(path):]
        return '%s="%s"' % (m.group(1), url)
    return re.sub(r'\b(src|href)="([^"]*)"', fix, html)


def number(html):
    """data-n="- N -" on every div.page that is not a cover"""
    n = [0]
    def page(m):
        cls = m.group(1).split()
        if "page" not in cls or "cover" in cls:
            return m.group(0)
        n[0] += 1
        return '<div data-n="— %d —" class="%s"' % (n[0], m.group(1))
    return re.sub(r'<div class="([^"]*)"', page, html), n[0]


def overflow(document):
    """[(page number, mm)] of the pages whose content goes past the bottom of the page box (WeasyPrint layout); best effort"""
    def walk(box):
        yield box
        for c in getattr(box, "children", []) or []:
            if c.style["position"] not in ("absolute", "fixed"):      # page number (::after) and other placed boxes
                yield from walk(c)
    res = []
    for i, page in enumerate(document.pages, 1):
        for b in walk(page._page_box):
            el = getattr(b, "element", None)
            if el is None or "page" not in (el.get("class") or "").split() or b.element_tag != "div":
                continue
            bottom = b.content_box_y() + b.height
            low = max((d.position_y + d.margin_height() for d in walk(b) if d is not b and hasattr(d, "margin_height")), default=0)
            if low - bottom > 0.5:
                res.append((i, (low - bottom) * 25.4 / 96))
            break
    return res


def build(src=None, values=None, out_dir=None, pdf_name=None, html_name=None, theme=None, base=None, fmt=None, html_only=False,
          strict=False):
    """builds one manual; returns (html path, pdf path or None, numbered pages)"""
    src = src or sources()[0]
    if not os.path.isfile(src):
        sys.exit("manual: source %s not found (C64_MANUAL_SRC in lab64.env)" % src)
    out_dir = out_dir or OUT
    stem = os.path.splitext(os.path.basename(src))[0]
    html = open(src, encoding="utf-8").read()
    sdir = os.path.dirname(os.path.abspath(src))
    pdf_name = pdf_name or meta(html, "pdf") or (setting("C64_MANUAL_PDF") if len(sources()) == 1 else None) or stem + ".pdf"
    html_name = html_name or stem + ".html"
    theme = theme or (os.path.join(sdir, meta(html, "theme")) if meta(html, "theme") else setting("C64_MANUAL_THEME"))
    base = base or meta(html, "base")
    fmt = fmt or meta(html, "format")
    os.makedirs(out_dir, exist_ok=True)
    problems = []
    for k, v in (values or {}).items():
        ph = "{{%s}}" % k
        if ph not in html:
            sys.exit("manual: placeholder %s missing in %s" % (ph, src))
        html = html.replace(ph, str(v))
    for ph in sorted(set(re.findall(r"\{\{[A-Z0-9_]+\}\}", html))):
        problems.append("placeholder %s has no value" % ph)
    html = relink(html, sdir, os.path.abspath(out_dir))
    css = themes(base, theme, fmt)
    style = "<style>\n%s\n</style>\n" % css
    m = re.search(r"<head[^>]*>", html, re.I)
    html = html[:m.end()] + "\n" + style + html[m.end():] if m else style + html
    face, ink, shadow = var(css, "key-face", "#fffaf0"), var(css, "key-ink", "#2a2118"), var(css, "key-shadow", "#2a2118")
    html = re.sub(r"<kbd>(.*?)</kbd>", lambda k: kbd(k.group(1), face, ink, shadow), html, flags=re.S)
    html, pages = number(html)
    hp = os.path.join(out_dir, html_name)
    open(hp, "w", encoding="utf-8").write(html)
    pp = None
    if not html_only:
        import logging
        logging.getLogger("weasyprint").setLevel(logging.ERROR)   # known warnings: text-shadow, print-color-adjust
        import weasyprint
        doc = weasyprint.HTML(hp).render()
        pp = os.path.join(out_dir, pdf_name)
        doc.write_pdf(pp)
        try:
            for i, mm in overflow(doc):
                problems.append("page %d of the PDF overflows by %.1f mm (content cut)" % (i, mm))
        except Exception as e:                                # it uses WeasyPrint internals: it may break with a new version
            if strict:                                        # a release build must not pass unchecked
                problems.append("overflow check could not run (%s: %s)" % (type(e).__name__, e))
            else:
                print("manual: WARNING overflow check skipped (%s: %s)" % (type(e).__name__, e))
    for p in problems:
        print("manual: %s %s (%s)" % ("ERROR" if strict else "WARNING", p, os.path.basename(src)))
    if strict and problems:
        sys.exit(1)
    return hp, pp, pages


def main(argv):
    import argparse
    ap = argparse.ArgumentParser(prog="lab64 manual", description="C64 instruction manuals: HTML source -> HTML + PDF")
    ap.add_argument("src", nargs="*", help="HTML sources (default: all of C64_MANUAL_SRC, or manual/manual.html)")
    ap.add_argument("--out", help="output folder (default out/work/manual)")
    ap.add_argument("--pdf", help="PDF file name (one source only; default: meta lab64:pdf, C64_MANUAL_PDF, <source name>.pdf)")
    ap.add_argument("--theme", help="project CSS loaded after the base theme (default: meta lab64:theme, C64_MANUAL_THEME)")
    ap.add_argument("--base", help="Lab64 base theme name or 'none' (default: meta lab64:base, C64_MANUAL_BASE, c64)")
    ap.add_argument("--format", help="page format A4, A5, A6, Letter or <w>x<h> mm (default: meta lab64:format, C64_MANUAL_FORMAT, A5)")
    ap.add_argument("--html", action="store_true", help="only the HTML, no PDF")
    ap.add_argument("--strict", action="store_true", help="exit 1 on an overflowing page, a placeholder without value or an overflow check that cannot run")
    a = ap.parse_args(argv)
    srcs = a.src or sources()
    if a.pdf and len(srcs) > 1:
        sys.exit("manual: --pdf with one source only")
    for src in srcs:
        hp, pp, n = build(src, out_dir=a.out, pdf_name=a.pdf, theme=a.theme, base=a.base, fmt=a.format, html_only=a.html,
                          strict=a.strict)
        print("manual: %s%s (%d numbered pages)" % (hp, ", " + pp if pp else "", n))


if __name__ == "__main__":
    main(sys.argv[1:])
